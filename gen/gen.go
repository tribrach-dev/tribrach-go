// Package gen writes Go DTOs, decoders and encoders from the JSON Schemas
// that core exports (Tribrach.Schema). It understands the subset core
// emits, and refuses anything else rather than guess:
//
//   - closed objects of scalar fields, required or optional;
//   - tagged unions: oneOf objects told apart by a constant field;
//   - booleans, bounded integers (with multipleOf), strings with lengths and
//     one of core's named patterns, enums;
//   - whole numbers as decimal strings (bounds under x-tribrach), which
//     become int64;
//   - RFC 3339 instants, which become time.Time.
//
// The generated decoders call package wire, which reads JSON the way core's
// Lean decoders do.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"

	"github.com/tribrach-dev/tribrach-go/wire"
)

// Spec names one schema to generate.
type Spec struct {
	Name   string // Go type name, such as StartRequest
	Source string // where the schema came from, for the header
	Schema []byte
}

type schema = map[string]any

// Generate returns a formatted Go file in package pkg.
func Generate(pkg string, specs []Spec) ([]byte, error) {
	g := &gen{}
	g.p("// Code generated by tribrach-go gen; DO NOT EDIT.")
	g.p("//")
	g.p("// Sources:")
	for _, s := range specs {
		g.p("//   - %s", s.Source)
	}
	g.p("")
	g.p("package %s", pkg)
	g.p("")
	head := g.buf.Len()
	for _, s := range specs {
		var sc schema
		if err := json.Unmarshal(s.Schema, &sc); err != nil {
			return nil, fmt.Errorf("%s: %w", s.Source, err)
		}
		if err := g.top(s.Name, sc); err != nil {
			return nil, fmt.Errorf("%s: %w", s.Source, err)
		}
	}
	imports := "import (\n\t\"encoding/json\"\n"
	if g.usesTime {
		imports += "\t\"time\"\n"
	}
	imports += "\n\ttw \"github.com/tribrach-dev/tribrach-go/wire\"\n)\n"
	src := g.buf.String()
	src = src[:head] + "\n" + imports + src[head:]
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w\n%s", err, g.buf.String())
	}
	return out, nil
}

type gen struct {
	buf      bytes.Buffer
	usesTime bool
}

func (g *gen) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

// GoName turns a JSON field or case name into an exported Go name.
func GoName(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '-' || r == '_' || r == '.' {
			up = true
			continue
		}
		if up {
			b.WriteRune(unicode.ToUpper(r))
			up = false
		} else {
			b.WriteRune(r)
		}
	}
	n := b.String()
	if strings.HasSuffix(n, "Id") {
		n = strings.TrimSuffix(n, "Id") + "ID"
	}
	return n
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func comment(text string) string { return strings.ReplaceAll(text, "\n", "\n// ") }

func (g *gen) top(name string, sc schema) error {
	id, _ := sc["$id"].(string)
	title, _ := sc["title"].(string)
	g.p("")
	g.p("const %sSchema = %q", lowerFirst(name), id)
	g.p("")
	g.p("// Decode%s reads a %s, rejecting anything its schema rejects.", name, title)
	g.p("func Decode%s(data []byte) (%s, error) {", name, name)
	g.p("\tvar zero %s", name)
	g.p("\tdoc, err := tw.Parse(data)")
	g.p("\tif err != nil {")
	g.p("\t\treturn zero, &tw.Error{Schema: %sSchema, Reason: err.Error()}", lowerFirst(name))
	g.p("\t}")
	g.p("\tr := &tw.Reader{Schema: %sSchema}", lowerFirst(name))
	g.p("\tv := read%s(r, doc, \"\")", name)
	g.p("\tif r.Err != nil {")
	g.p("\t\treturn zero, r.Err")
	g.p("\t}")
	g.p("\treturn v, nil")
	g.p("}")
	g.p("")
	g.p("// Encode%s writes a %s. It fails rather than write JSON its own", name, title)
	g.p("// schema would reject.")
	g.p("func Encode%s(v %s) ([]byte, error) {", name, name)
	g.p("\tdata, err := json.Marshal(write%s(v))", name)
	g.p("\tif err != nil {")
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\tif _, err := Decode%s(data); err != nil {", name)
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\treturn data, nil")
	g.p("}")
	if alts, ok := sc["oneOf"].([]any); ok {
		return g.union(name, title, id, sc, alts)
	}
	if sc["type"] == "object" {
		return g.object(name, title, id, sc, "")
	}
	return fmt.Errorf("the top level must be an object or a tagged union")
}

// fields returns an object's properties in a stable order: required first,
// in the schema's order, then optional ones alphabetically.
func fields(sc schema) (names []string, required map[string]bool) {
	props, _ := sc["properties"].(map[string]any)
	required = map[string]bool{}
	if req, ok := sc["required"].([]any); ok {
		for _, r := range req {
			s := r.(string)
			required[s] = true
			names = append(names, s)
		}
	}
	var opt []string
	for k := range props {
		if !required[k] {
			opt = append(opt, k)
		}
	}
	sort.Strings(opt)
	return append(names, opt...), required
}

func (g *gen) object(name, title, id string, sc schema, tag string) error {
	if sc["additionalProperties"] != false {
		return fmt.Errorf("%s: objects must be closed (additionalProperties: false)", name)
	}
	props, _ := sc["properties"].(map[string]any)
	names, required := fields(sc)
	type field struct {
		json, goName, goType string
		f                    scalar
		required             bool
	}
	var fs []field
	for _, n := range names {
		if n == tag {
			continue
		}
		ps, ok := props[n].(map[string]any)
		if !ok {
			return fmt.Errorf("%s.%s: no schema for a required field", name, n)
		}
		f, err := scalarOf(ps)
		if f.goType == "time.Time" {
			g.usesTime = true
		}
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, n, err)
		}
		t := f.goType
		if !required[n] {
			t = "*" + t
		}
		fs = append(fs, field{n, GoName(n), t, f, required[n]})
	}
	g.p("")
	if title != "" {
		g.p("// %s is a %s.", name, title)
	}
	if id != "" {
		g.p("// Schema: %s", id)
	}
	g.p("type %s struct {", name)
	for _, f := range fs {
		if f.f.doc != "" {
			g.p("\t// %s", comment(f.f.doc))
		}
		// No json tags: encoding/json would write these fields in the
		// wrong shape (money as numbers, instants with fractions). Use the
		// generated Encode and Decode functions.
		g.p("\t%s %s // %q", f.goName, f.goType, f.json)
	}
	g.p("}")
	keys := make([]string, 0, len(names))
	for _, n := range names {
		keys = append(keys, fmt.Sprintf("%q", n))
	}
	g.p("")
	g.p("func read%s(r *tw.Reader, doc any, path string) %s {", name, name)
	g.p("\tvar out %s", name)
	g.p("\tm := r.Object(doc, path, %s)", strings.Join(keys, ", "))
	g.p("\tif m == nil {")
	g.p("\t\treturn out")
	g.p("\t}")
	for _, f := range fs {
		p := fmt.Sprintf("tw.Join(path, %q)", f.json)
		if f.required {
			g.p("\tout.%s = %s", f.goName, f.f.read(fmt.Sprintf("r.Field(m, path, %q)", f.json), p))
		} else {
			g.p("\tif v, ok := tw.Optional(m, %q); ok {", f.json)
			g.p("\t\tx := %s", f.f.read("v", p))
			g.p("\t\tout.%s = &x", f.goName)
			g.p("\t}")
		}
	}
	g.p("\treturn out")
	g.p("}")
	g.p("")
	g.p("func write%s(v %s) map[string]any {", name, name)
	g.p("\tm := map[string]any{}")
	for _, f := range fs {
		if f.required {
			g.p("\tm[%q] = %s", f.json, f.f.write("v."+f.goName))
		} else {
			g.p("\tif v.%s != nil {", f.goName)
			g.p("\t\tm[%q] = %s", f.json, f.f.write("(*v."+f.goName+")"))
			g.p("\t}")
		}
	}
	g.p("\treturn m")
	g.p("}")
	return nil
}

func (g *gen) union(name, title, id string, sc schema, alts []any) error {
	tag := ""
	var cases []string
	var objs []schema
	for _, a := range alts {
		o, ok := a.(map[string]any)
		if !ok || o["type"] != "object" {
			return fmt.Errorf("%s: oneOf alternatives must be objects", name)
		}
		props, _ := o["properties"].(map[string]any)
		found := ""
		for k, v := range props {
			if c, ok := v.(map[string]any)["const"].(string); ok {
				if found != "" {
					return fmt.Errorf("%s: an alternative has two constant fields", name)
				}
				found = k
				cases = append(cases, c)
			}
		}
		if found == "" || (tag != "" && found != tag) {
			return fmt.Errorf("%s: alternatives must share one constant tag field", name)
		}
		tag = found
		objs = append(objs, o)
	}
	seen := map[string]bool{}
	for _, c := range cases {
		if seen[c] {
			return fmt.Errorf("%s: two alternatives share the tag %q", name, c)
		}
		seen[c] = true
	}
	g.p("")
	g.p("// %s is a %s: one of", name, title)
	for _, c := range cases {
		g.p("// %s%s,", name, GoName(c))
	}
	g.p("// told apart on the wire by %q.", tag)
	g.p("// Schema: %s", id)
	g.p("type %s interface{ is%s() }", name, name)
	quoted := make([]string, len(cases))
	for i, c := range cases {
		quoted[i] = fmt.Sprintf("%q", c)
	}
	g.p("")
	g.p("func read%s(r *tw.Reader, doc any, path string) %s {", name, name)
	g.p("\tswitch r.Tag(doc, path, %q, %s) {", tag, strings.Join(quoted, ", "))
	for _, c := range cases {
		g.p("\tcase %q:", c)
		g.p("\t\treturn read%s%s(r, doc, path)", name, GoName(c))
	}
	g.p("\t}")
	g.p("\treturn nil")
	g.p("}")
	g.p("")
	g.p("func write%s(v %s) map[string]any {", name, name)
	g.p("\tswitch x := v.(type) {")
	for _, c := range cases {
		g.p("\tcase %s%s:", name, GoName(c))
		g.p("\t\tm := write%s%s(x)", name, GoName(c))
		g.p("\t\tm[%q] = %q", tag, c)
		g.p("\t\treturn m")
	}
	g.p("\t}")
	g.p("\treturn nil")
	g.p("}")
	for i, c := range cases {
		cn := name + GoName(c)
		if err := g.object(cn, fmt.Sprintf("%s case %q", title, c), "", objs[i], tag); err != nil {
			return err
		}
		g.p("")
		g.p("func (%s) is%s() {}", cn, name)
	}
	return nil
}

// scalar is how one field reads and writes.
type scalar struct {
	goType string
	doc    string
	read   func(v, path string) string
	write  func(v string) string
}

func num(v any) (int64, bool) {
	f, ok := v.(float64)
	if !ok || f != float64(int64(f)) {
		return 0, false
	}
	return int64(f), true
}

func ptrExpr(v any) string {
	if n, ok := num(v); ok {
		return fmt.Sprintf("tw.Ptr(%d)", n)
	}
	return "nil"
}

var known = map[string]bool{
	"type": true, "description": true, "minimum": true, "maximum": true, "multipleOf": true,
	"minLength": true, "maxLength": true, "pattern": true, "format": true, "enum": true,
	"x-tribrach": true,
}

func scalarOf(ps schema) (scalar, error) {
	for k := range ps {
		if !known[k] {
			return scalar{}, fmt.Errorf("unsupported keyword %q", k)
		}
	}
	doc, _ := ps["description"].(string)
	same := func(v string) string { return v }
	if vals, ok := ps["enum"].([]any); ok {
		qs := make([]string, len(vals))
		for i, v := range vals {
			s, ok := v.(string)
			if !ok {
				return scalar{}, fmt.Errorf("only string enums are supported")
			}
			qs[i] = fmt.Sprintf("%q", s)
		}
		return scalar{"string", doc, func(v, p string) string {
			return fmt.Sprintf("r.Enum(%s, %s, %s)", v, p, strings.Join(qs, ", "))
		}, same}, nil
	}
	switch ps["type"] {
	case "boolean":
		return scalar{"bool", doc, func(v, p string) string { return fmt.Sprintf("r.Bool(%s, %s)", v, p) }, same}, nil
	case "integer":
		m, _ := num(ps["multipleOf"])
		b := fmt.Sprintf("tw.IntBounds{Min: %s, Max: %s, MultipleOf: %d}", ptrExpr(ps["minimum"]), ptrExpr(ps["maximum"]), m)
		return scalar{"int64", doc, func(v, p string) string { return fmt.Sprintf("r.Int(%s, %s, %s)", v, p, b) }, same}, nil
	case "string":
		regex, _ := ps["pattern"].(string)
		if regex == "" {
			if _, has := ps["format"]; has {
				return scalar{}, fmt.Errorf("a format without a pattern isn't checkable")
			}
		}
		pat := wire.Pattern{}
		if regex != "" {
			var ok bool
			if pat, ok = wire.PatternByRegex(regex); !ok {
				return scalar{}, fmt.Errorf("TRG0403 unknown pattern %q: core's patterns (Tribrach.Schema.Pat) are a closed list; fix: update tribrach-go to the core version that exported this schema", regex)
			}
		}
		x, _ := ps["x-tribrach"].(map[string]any)
		switch pat.Name {
		case "decimal":
			b := fmt.Sprintf("tw.IntBounds{Min: %s, Max: %s}", ptrExpr(x["minimum"]), ptrExpr(x["maximum"]))
			return scalar{"int64", doc, func(v, p string) string { return fmt.Sprintf("r.Decimal(%s, %s, %s)", v, p, b) },
				func(v string) string { return "tw.FormatDecimal(" + v + ")" }}, nil
		case "instant":
			if _, has := ps["minLength"]; has {
				return scalar{}, fmt.Errorf("lengths on an instant aren't supported")
			}
			return scalar{"time.Time", doc, func(v, p string) string { return fmt.Sprintf("r.Instant(%s, %s)", v, p) },
				func(v string) string { return "tw.FormatInstant(" + v + ")" }}, nil
		}
		if x != nil {
			return scalar{}, fmt.Errorf("x-tribrach bounds only apply to decimal strings")
		}
		b := fmt.Sprintf("tw.StrBounds{MinLen: %s, MaxLen: %s", ptrExpr(ps["minLength"]), ptrExpr(ps["maxLength"]))
		if pat.Name != "" {
			b += fmt.Sprintf(", Pattern: %q", pat.Name)
		}
		b += "}"
		return scalar{"string", doc, func(v, p string) string { return fmt.Sprintf("r.String(%s, %s, %s)", v, p, b) }, same}, nil
	}
	return scalar{}, fmt.Errorf("unsupported field schema (arrays and nested objects come later)")
}
